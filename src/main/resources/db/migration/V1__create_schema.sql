-- Esquema do Marco 1 (data-model.md). SQL portável entre H2 e PostgreSQL, sem funções específicas.

CREATE TABLE movie (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_year INTEGER       NOT NULL,
    title        VARCHAR(500)  NOT NULL,
    studios      VARCHAR(1000),
    producers    VARCHAR(1000) NOT NULL,
    winner       BOOLEAN       NOT NULL,
    CONSTRAINT uk_movie_year_title UNIQUE (release_year, title)
);

CREATE TABLE producer (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(500) NOT NULL,
    CONSTRAINT uk_producer_name UNIQUE (name)
);

CREATE TABLE movie_producer (
    movie_id    BIGINT NOT NULL,
    producer_id BIGINT NOT NULL,
    CONSTRAINT pk_movie_producer PRIMARY KEY (movie_id, producer_id),
    CONSTRAINT fk_movie_producer_movie FOREIGN KEY (movie_id) REFERENCES movie (id),
    CONSTRAINT fk_movie_producer_producer FOREIGN KEY (producer_id) REFERENCES producer (id)
);
